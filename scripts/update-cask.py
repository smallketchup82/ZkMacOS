"""Publish a versioned Homebrew cask from a released DMG and its checksum."""
from pathlib import Path
from datetime import date
import argparse
import hashlib
import json
import os
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
ASSET = 'Zero-K-macOS-arm64.dmg'


def release_version(tag):
    match = re.fullmatch(r'([0-9]{4})([0-9]{2})\.([0-9]{2})\.(0|[1-9][0-9]*)', tag)
    if not match:
        raise ValueError('Use YYYYMM.DD.PATCH, such as 202610.27.0; prerelease tags are not supported.')
    date(int(match[1]), int(match[2]), int(match[3]))
    return tag


def update_cask(tag, dmg, checksum, output, repository):
    version = release_version(tag)
    if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', repository):
        raise ValueError('Expected a GitHub owner/repository.')
    fields = checksum.read_text().split()
    if len(fields) != 2 or fields[1] != ASSET or not re.fullmatch(r'[a-fA-F0-9]{64}', fields[0]):
        raise ValueError('Expected a SHA256 checksum for ' + ASSET)
    with dmg.open('rb') as source:
        digest = hashlib.file_digest(source, 'sha256').hexdigest()
    if digest != fields[0].lower():
        raise ValueError('Release DMG does not match its published checksum.')

    if output.exists():
        previous = output.read_text()
        old_version = re.search(r'^  version "([0-9.]+)"$', previous, re.MULTILINE)
        if not old_version:
            raise ValueError('Existing cask has an unrecognized version.')
        old_numbers = tuple(map(int, old_version[1].split('.')))
        new_numbers = tuple(map(int, version.split('.')))
        if new_numbers < old_numbers:
            print('Skipping older release ' + tag)
            return False
        if new_numbers == old_numbers:
            if f'  sha256 "{digest}"' not in previous:
                raise ValueError('Do not replace an existing release; publish a new version.')
            print('Cask already matches ' + tag)
            return False

    cask = f'''# Generated by scripts/update-cask.py from a published GitHub release.
cask "zkmacos" do
  version "{version}"
  sha256 "{digest}"

  url "https://github.com/{repository}/releases/download/{tag}/{ASSET}"
  name "ZkMacOS"
  desc "Unofficial, experimental Apple Silicon port of Zero-K"
  homepage "https://github.com/{repository}"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on arch: :arm64
  depends_on macos: :tahoe

  auto_updates true

  app "Zero-K.app"

  caveats <<~EOS
    This experimental third-party client is not supported by the Zero-K developers.
    Report port bugs at https://github.com/{repository}/issues.
    The app is not Developer ID signed or notarized; macOS may require approval.
    Settings and downloads remain in ~/Library/Application Support/Zero-K.
  EOS
end
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(cask)
    print(f'Updated {output} to {version}')
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tag', required=True)
    parser.add_argument('--repository', default=os.environ.get('GITHUB_REPOSITORY', 'smallketchup82/ZkMacOS'))
    args = parser.parse_args()
    release_version(args.tag)
    if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', args.repository):
        raise ValueError('Expected a GitHub owner/repository.')
    release = json.loads(subprocess.check_output([
        'gh', 'api', f'repos/{args.repository}/releases/tags/{args.tag}',
    ], text=True))
    if release['draft'] or release['prerelease']:
        raise ValueError('Only published, non-prerelease releases update the Homebrew cask.')
    names = {asset['name'] for asset in release['assets']}
    if not {ASSET, ASSET + '.sha256'}.issubset(names):
        raise ValueError('Attach the DMG and its .sha256 file before publishing the release.')
    with tempfile.TemporaryDirectory(prefix='zkmacos-cask-') as temporary:
        directory = Path(temporary)
        subprocess.run([
            'gh', 'release', 'download', args.tag, '--repo', args.repository,
            '--pattern', ASSET, '--pattern', ASSET + '.sha256', '--dir', temporary,
        ], check=True)
        update_cask(args.tag, directory / ASSET, directory / (ASSET + '.sha256'),
                    ROOT / 'Casks/zkmacos.rb', args.repository)


if __name__ == '__main__':
    main()
